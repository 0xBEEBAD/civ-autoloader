#!/usr/bin/env python3
"""Generate the NRO's embedded assets from our payloads.

Outputs:
  source/chat_payload.h       core.js + UDP receiver, compressed for chat
  source/installer_payload.h  CivSwitchFS persist bootstrap + save staging
  data/save_template.bin      pristine Civ7 save template

The NRO uploads the template over TCP 9026 as `window.__tpl` chunks, then
runs `installer_apply_js`. That script evaluates the persist bootstrap,
feeds the staged chunks to `stageChunk()`, and calls `installFromTemplate()`.

The apply script ends with the `INSTALL DONE` marker that installer.c waits
for, so the NRO reports success only after the save is committed.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                        # packages/transport/nro
PROJECT = os.path.dirname(os.path.dirname(os.path.dirname(ROOT)))
BUILD_PAYLOAD = os.path.join(PROJECT, "packages", "transport", "build-payload.js")

CHUNK = 400_000          # base64 chars per stageChunk call (multiple of 4)
MAX_LINE = 1000
DONE_MARKER = "INSTALL DONE"

ADAPTER = r"""
;(async function () {
try {
    var tplB64 = (window.__tpl || []).join("");
    if (!window.__cfsPersistInstaller) {
        await log("E: persist installer is unavailable");
        return;
    }
    if (tplB64.length !== __TPL_LEN__) {
        await log("E: template upload incomplete (" + tplB64.length +
                  " of __TPL_LEN__)");
        return;
    }
    window.__tpl = null;
    for (var offset = 0, index = 0; offset < tplB64.length;
         offset += __CHUNK__, index++) {
        window.__cfsPersistInstaller.stageChunk("nro", index, offset,
            tplB64.slice(offset, offset + __CHUNK__));
    }
    await window.__cfsPersistInstaller.installFromTemplate();
    await log("__DONE__");
} catch (error) {
    await log("E: " + (error && error.message ? error.message : error));
}
})();
""".replace("__CHUNK__", str(CHUNK)).replace("__DONE__", DONE_MARKER)


def c_lines(text: str, width: int = 96) -> str:
    return "\n".join("    " + json.dumps(text[i:i + width])
                     for i in range(0, len(text), width))


def c_escape(text: str) -> str:
    return (text.replace("\\", "\\\\")
                .replace('"', '\\"')
                .replace("?", "\\?"))


def write_chat_payload(out_path: str) -> int:
    lines = json.loads(subprocess.run(
        ["node", BUILD_PAYLOAD], check=True, capture_output=True, text=True
    ).stdout)
    for line in lines:
        if len(line) + 1 > MAX_LINE:
            raise SystemExit(f"chat line is {len(line) + 1} bytes (limit {MAX_LINE})")

    with open(out_path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("// Generated by tools/generate_assets.py -- do not edit.\n")
        fh.write("// Source: third_party/CivSwitch/core.js + the UDP receiver.\n")
        fh.write("#ifndef CIVSWITCH_CHAT_PAYLOAD_H\n#define CIVSWITCH_CHAT_PAYLOAD_H\n\n")
        fh.write("static const char *const chat_payload_lines[] = {\n")
        for line in lines:
            fh.write('    "%s",\n' % c_escape(line))
        fh.write("};\n\n")
        fh.write("static const unsigned chat_payload_count = "
                 "sizeof(chat_payload_lines) / sizeof(chat_payload_lines[0]);\n\n")
        fh.write("#endif\n")
    return len(lines)


def write_installer_payload(bootstrap_path: str, template_path: str,
                            out_header: str, out_template: str) -> int:
    with open(bootstrap_path, encoding="ascii") as fh:
        bootstrap = fh.read()
    with open(template_path, "rb") as fh:
        template = fh.read()
    if len(template) < 4096 or template[:4] != b"CIV7":
        raise SystemExit(f"{template_path} is not a Civ7 save template")

    template_b64 = ((len(template) + 2) // 3) * 4
    apply_js = (bootstrap.rstrip() + "\n" +
                ADAPTER.replace("__TPL_LEN__", str(template_b64)))

    with open(out_template, "wb") as fh:
        fh.write(template)

    with open(out_header, "w", encoding="ascii", newline="\n") as fh:
        fh.write("// Generated by tools/generate_assets.py -- do not edit.\n")
        fh.write("// CivSwitchFS persist bootstrap (MIT) + save staging adapter.\n")
        fh.write("#ifndef CIVSWITCH_INSTALLER_PAYLOAD_H\n")
        fh.write("#define CIVSWITCH_INSTALLER_PAYLOAD_H\n\n")
        fh.write("static const char installer_apply_js[] =\n")
        fh.write(c_lines(apply_js))
        fh.write(";\n\n")
        fh.write("static const unsigned installer_template_base64_length = %uU;\n\n"
                 % template_b64)
        fh.write("#endif\n")
    return len(apply_js)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cfs",
                    default=os.path.join(PROJECT, "third_party", "CivSwitchFS"),
                    help="CivSwitchFS checkout")
    ap.add_argument("--no-build", action="store_true",
                    help="use an existing dist/persist build")
    args = ap.parse_args()

    if not args.no_build:
        subprocess.run(["npm", "run", "persist:build"], cwd=args.cfs, check=True)

    bootstrap = os.path.join(args.cfs, "dist", "persist", "persist-bootstrap.js")
    template = os.path.join(args.cfs, "dist", "persist", "save-template.bin")
    for path in (bootstrap, template):
        if not os.path.isfile(path):
            print(f"E: missing {path}", file=sys.stderr)
            return 1

    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    chat = write_chat_payload(os.path.join(ROOT, "source", "chat_payload.h"))
    apply_bytes = write_installer_payload(
        bootstrap, template,
        os.path.join(ROOT, "source", "installer_payload.h"),
        os.path.join(ROOT, "data", "save_template.bin"))

    print(f"chat payload: {chat} lines")
    print(f"installer apply: {apply_bytes} bytes")
    print("wrote source/chat_payload.h, source/installer_payload.h, "
          "data/save_template.bin")
    return 0


if __name__ == "__main__":
    sys.exit(main())
